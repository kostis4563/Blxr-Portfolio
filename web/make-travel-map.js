import { readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import { geoCentroid, geoNaturalEarth1, geoPath } from 'd3-geo'
import { feature } from 'topojson-client'
import { presimplify, simplify, quantile, sphericalTriangleArea } from 'topojson-simplify'

const here = dirname(fileURLToPath(import.meta.url))
const out = resolve(here, 'src/lib/travel-map.js')
const require = createRequire(import.meta.url)

const WIDTH = 1000
const KEEP = 0.6

const raw = presimplify(JSON.parse(await readFile(require.resolve('world-atlas/countries-110m.json'), 'utf8')), sphericalTriangleArea)
const world = simplify(raw, quantile(raw, KEEP))
// France's shape includes French Guiana; give it its own entry so visiting France does not light up South America.
const splitOverseas = (f) => {
  if (f.properties.name !== 'France' || f.geometry.type !== 'MultiPolygon') return [f]
  const parts = f.geometry.coordinates.map((coordinates) => ({ type: 'Polygon', coordinates }))
  const far = (g) => geoCentroid(g)[0] < -20
  return [
    { ...f, geometry: { type: 'MultiPolygon', coordinates: parts.filter((g) => !far(g)).map((g) => g.coordinates) } },
    { ...f, properties: { name: 'French Guiana' }, geometry: { type: 'MultiPolygon', coordinates: parts.filter(far).map((g) => g.coordinates) } },
  ]
}
const countries = feature(world, world.objects.countries)
  .features.filter((f) => f.properties.name !== 'Antarctica')
  .flatMap(splitOverseas)
const collection = { type: 'FeatureCollection', features: countries }

const projection = geoNaturalEarth1().fitWidth(WIDTH, collection)
const path = geoPath(projection).digits(0)
const [[, top], [, bottom]] = path.bounds(collection)
projection.translate([projection.translate()[0], projection.translate()[1] - top])
const height = Math.ceil(bottom - top)

const shapes = {}
for (const country of countries) {
  const d = path(country)
  if (d) shapes[country.properties.name] = (shapes[country.properties.name] || '') + d
}

const body = `// Generated by make-travel-map.js from Natural Earth 1:110m (world-atlas). Do not edit by hand.

export const MAP_WIDTH = ${WIDTH}
export const MAP_HEIGHT = ${height}

export const MAP_COUNTRIES = {
${Object.keys(shapes).sort().map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(shapes[name])},`).join('\n')}
}
`

await writeFile(out, body)
console.log(`travel map: ${Object.keys(shapes).length} countries, ${WIDTH}×${height}, ${(body.length / 1024).toFixed(1)} KB -> ${out}`)
